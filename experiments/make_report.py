"""Generates docs/RESULTS.md from run artifacts. No number in the report is typed by hand (spec rule 3)."""
import glob, json
from pathlib import Path
from common import ROOT

def latest(exp):
    fs = glob.glob(str(ROOT / f"experiments/runs/{exp}/*/results.json"))
    if not fs: return (None, None)

    def sort_key(p: str):
        manifest = Path(p).parent / "manifest.json"
        try:
            created = str(json.loads(manifest.read_text()).get("created_utc", ""))
        except (OSError, ValueError):
            created = ""
        return (created, Path(p).stat().st_mtime)

    newest = max(fs, key=sort_key)
    return (json.loads(Path(newest).read_text()), Path(newest).parent.relative_to(ROOT))

