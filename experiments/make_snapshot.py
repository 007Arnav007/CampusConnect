"""Trains linear utility models on DES logs, signs an Ed25519 policy snapshot and writes golden evaluator vectors for the gateway."""
import json, base64
import numpy as np
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from common import ROOT
from e6_policy import CRIT, REPS, run_context, sample_context
from src.delivery import policy as pol
from src.delivery import snapshot as snap
from src.delivery.des import utility

rng = np.random.default_rng(8001); X, U = [], {a: [] for a in CRIT}
for i in range(1200):
    p, c = sample_context(rng); res = run_context(p, c, 8001 + i, CRIT, 0.05)
    X.append(pol.context_vector(c, True))
    for a in CRIT: U[a].append(float(np.mean([utility(o, c["severity"], c["deadline_ms"]) for o in res[a]])))
X = np.array(X); spec, models = snap.fit_linear_utilities(X, {a: np.array(v) for a, v in U.items()})
key = Ed25519PrivateKey.from_private_bytes(bytes(range(32)))     # DEMO KEY ONLY: fixture for tests. Production keys are generated by `campusctl keys`.
s = snap.make_snapshot(spec, models, key, ttl_s=10**9, snapshot_id="snap-demo-0001", now=1_700_000_000.0)
body = snap.verify_snapshot(s, snap.public_key_b64(key), now=1_700_000_001.0); assert body is not None
vec = []
for _ in range(60):
    x = X[rng.integers(len(X))] * rng.uniform(0.9, 1.1, X.shape[1]); vec.append({"x": x.tolist(), "u": snap.evaluate(body, x), "ood": snap.is_ood(body, x)})
far = X[0] * 5; vec.append({"x": far.tolist(), "u": snap.evaluate(body, far), "ood": snap.is_ood(body, far)})
out = ROOT / "protocol/fixtures"; (out / "policy-snapshot.json").write_text(json.dumps(s)); (out / "snapshot-vectors.json").write_text(json.dumps({"publicKey": snap.public_key_b64(key), "vectors": vec}))
print("snapshot signed; ood flags:", sum(v["ood"] for v in vec), "of", len(vec))
